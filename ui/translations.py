def localized_evidence(language: str, agent: str, evidence: str) -> str:
    if language == "en":
        return evidence
    if agent == "Knowledge / RAG agent":
        return text(language, "knowledge_evidence")
    if evidence == "Photo screening is preliminary and not a verified pest classifier.":
        return text(language, "pest_note")
    labels = {
        "Selected crop": "evidence_crop",
        "Growth stage": "evidence_stage",
        "Photo received": "evidence_photo",
        "Entered soil moisture": "evidence_soil",
        "Entered rain forecast": "evidence_forecast",
        "Entered temperature": "evidence_temperature",
        "Entered wind": "evidence_wind",
        "Recent rainfall": "evidence_recent_rain",
        "Soil moisture": "evidence_soil",
        "Forecast rain": "evidence_forecast",
        "Field area": "evidence_area",
    }
    label, separator, value = evidence.partition(":")
    key = labels.get(label)
    if not key or not separator:
        return text(language, "generic_evidence")
    if label == "Selected crop":
        value = crop_label(language, value.strip())
    elif label == "Growth stage":
        value = stage_label(language, value.strip())
    elif label == "Photo received":
        value = value.strip().replace("KB", "کلو بائٹ")
    else:
        value = (
            value.replace("km/h", "کلومیٹر فی گھنٹہ")
            .replace("mm", "ملی میٹر")
            .replace(" acres", " ایکڑ")
            .replace(" C", " سینٹی گریڈ")
        )
    return f"{text(language, key)}: {value.strip()}"


